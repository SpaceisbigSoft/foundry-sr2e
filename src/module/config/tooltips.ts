/** Put field tooltips on a sheet's labels (v0.41.0). */
export function applyFieldTooltips(root: HTMLElement | null | undefined, type: string): void {
  if (!root?.querySelectorAll) return;
  for (const el of Array.from(root.querySelectorAll<HTMLElement>('[name^="system."]'))) {
    const name = el.getAttribute('name') ?? '';
    const key = FIELD_TOOLTIPS[`${type}:${name}`] ?? FIELD_TOOLTIPS[name];
    if (!key) continue;
    const tip = tKey(key);
    const label = el.closest('label') ?? el;
    if (label.getAttribute('title') || label.dataset['tooltip']) continue;
    label.dataset['tooltip'] = tip;
  }
}
