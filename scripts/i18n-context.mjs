#!/usr/bin/env node
/**
 * v0.89.5: write the translators' context list, docs/TRANSLATING-PARTS.md: every text that is put into a placeholder
 * of another text (`tx('HOST', { part: tx('PIECE') })`), so a translator sees which pieces go into which sentence.
 * The pieces left are clauses that read on their own (a note in brackets, a sentence, a value); pieces that were only
 * words of a sentence were joined into whole texts in v0.89.5.
 *
 *   node scripts/i18n-context.mjs           write the file
 *   node scripts/i18n-context.mjs --check   exit 1 when the file is out of date
 */
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'docs', 'TRANSLATING-PARTS.md');
const CHECK = process.argv.includes('--check');
const flat = {};
const walkJ = (o, p) => { for (const [k, v] of Object.entries(o)) { if (typeof v === 'string') flat[p + k] = v; else if (v && typeof v === 'object') { if ('other' in v && typeof v.other === 'string') flat[p + k] = `${v.one ?? ''} | ${v.other}`; else walkJ(v, p + k + '.'); } } };
walkJ(JSON.parse(fs.readFileSync(path.join(ROOT, 'public', 'lang', 'en.json'), 'utf8')), '');

const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d).sort()) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) { if (f !== '__tests__') walk(p); } else if (f.endsWith('.ts')) files.push(p); } };
walk(path.join(ROOT, 'src', 'module'));

const keyOf = (n) => {
  if (!ts.isCallExpression(n) || !ts.isIdentifier(n.expression)) return null;
  const f = n.expression.text;
  const a = f === 'tCount' ? n.arguments[1] : (f === 'tx' || f === 'tHtml') ? n.arguments[0] : null;
  return a && ts.isStringLiteral(a) && a.text.startsWith('SR2E.') ? a.text : null;
};
const hosts = new Map(); // host -> Map(placeholder -> Set(piece))
for (const file of files) {
  const sf = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const visit = (n) => {
    const host = keyOf(n);
    if (host) {
      const f = n.expression.text;
      const data = f === 'tCount' ? n.arguments[2] : n.arguments[1];
      if (data && ts.isObjectLiteralExpression(data)) {
        for (const p of data.properties) {
          if (!ts.isPropertyAssignment(p)) continue;
          const pieces = new Set();
          const inner = (m) => { const k = keyOf(m); if (k) { pieces.add(k); return; } ts.forEachChild(m, inner); };
          inner(p.initializer);
          if (pieces.size) {
            const byPh = hosts.get(host) ?? new Map();
            const set = byPh.get(p.name.getText(sf)) ?? new Set();
            for (const k of pieces) set.add(k);
            byPh.set(p.name.getText(sf), set);
            hosts.set(host, byPh);
          }
        }
      }
    }
    ts.forEachChild(n, visit);
  };
  visit(sf);
}
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').replace(/</g, '&lt;');
const lines = [
  '# Texts that go into other texts',
  '',
  'Generated by `node scripts/i18n-context.mjs` (do not edit by hand). Each row is a text with a placeholder that the',
  'code fills with another text from `lang/en.json`. Translate each piece so it reads correctly in the place shown.',
  'See `docs/TRANSLATING.md` for the rest.',
  '',
  '| Text (key) | Placeholder | Pieces that go into it |',
  '|---|---|---|',
];
for (const host of [...hosts.keys()].sort()) {
  for (const [ph, set] of [...hosts.get(host).entries()].sort()) {
    lines.push(`| \`${host}\`: ${esc(flat[host])} | \`{${ph}}\` | ${[...set].sort().map((k) => `\`${k}\` (${esc(flat[k])})`).join('<br>')} |`);
  }
}
const text = lines.join('\n') + '\n';
if (CHECK) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('docs/TRANSLATING-PARTS.md is out of date: run node scripts/i18n-context.mjs'); process.exit(1); }
  console.log('context: ok');
} else { fs.writeFileSync(OUT, text); console.log(`context: ${lines.length - 8} rows`); }
